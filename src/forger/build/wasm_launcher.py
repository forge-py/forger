"""Self-contained WASM bundle launcher for emscripten targets.

The built bundle layout is::

    bundle/
    ├── runtime/
    │   └── bin/{python.wasm, python.mjs|python.js}
    ├── lib/pythonX.Y/        (pruned stdlib)
    ├── app/                  (.forge VFS tree)
    ├── run_app.mjs           (this launcher)
    └── BUNDLE.json

``run_app.mjs`` instantiates the Emscripten CPython runtime with a
preopen-mounted filesystem so ``sys.path`` resolves to the bundled
stdlib + app tree, then imports the entry module. It runs under plain
Node — no network, no external packages.
"""

from __future__ import annotations

from pathlib import Path

# JS glue: locate bundle dirs relative to the launcher, wire them into
# the Emscripten FS as preopens, set env for site handling, run entry.
# NOTE: this is a format template — literal JS braces are doubled.
_LAUNCHER_TEMPLATE = """\
// Forger WASM launcher - self-contained, requires only Node >= 18.
// Generated by `forger build --target emscripten-wasm`; do not edit.
import path from "node:path";
import {{ fileURLToPath }} from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const bin = path.join(here, "runtime", "bin");

let createModule;
try {{
  const mod = await import(
    "file://" + path.join(bin, "{glue_file}").replaceAll("\\\\", "/")
  );
  createModule = mod.default ?? mod;
}} catch (e) {{
  console.error("Forger: cannot load WASM glue:", e.message);
  process.exit(1);
}}

const PYVER = "{pyver}";

let Module;
try {{
  Module = await createModule({{
    print: (s) => process.stdout.write(s + "\\n"),
    printErr: (s) => process.stderr.write(s + "\\n"),
    locateFile: (p) => path.join(bin, p),
    noInitialRun: true,
  }});
}} catch (e) {{
  console.error("Forger: cannot instantiate WASM runtime:", e);
  process.exit(1);
}}

const FS = Module.FS;
FS.mkdirTree("/forger");
for (const [vpath, host] of [
  ["/forger/lib/python" + PYVER, path.join(here, "runtime", "lib", "python" + PYVER)],
  ["/forger/app", path.join(here, "app")],
]) {{
  try {{
    FS.mount(Module.NODEFS, {{ root: host.replaceAll("\\\\", "/") }}, vpath);
  }} catch (e) {{
    console.error("Forger: FS mount failed for " + vpath + ":", e.message);
    process.exit(1);
  }}
}}

Module.ENV.PYTHONHOME = "/forger";
Module.ENV.PYTHONPATH =
  "/forger/lib/python" + PYVER + ":/forger/lib/python" + PYVER +
  "/lib-dynload:/forger/app";
Module.ENV.FORGER_ENTRY = "{entry}";

let exitCode = 0;
try {{
  exitCode = Module.callMain([
    "-B",
    "-c",
    "import sys; sys.path.insert(0, '/forger/app'); import {entry}",
  ]);
}} catch (e) {{
  console.error("Forger app failed:", e);
  exitCode = 1;
}}
process.exit(exitCode);
"""


def emit_wasm_launcher(staging: Path, entry_point: str) -> Path:
    """Write ``run_app.mjs`` into the staged bundle and return its path.

    Detects which glue file the runtime actually ships so the launcher
    imports the right one.
    """
    glue = _detect_glue(staging)
    major_minor = _detect_python_version(staging)
    js = _LAUNCHER_TEMPLATE.format(
        glue_file=glue,
        pyver=major_minor,
        entry=entry_point,
    )
    target = staging / "run_app.mjs"
    target.write_text(js, encoding="utf-8")
    return target


def _detect_glue(staging: Path) -> str:
    bin_dir = staging / "runtime" / "bin"
    if not bin_dir.is_dir():
        return "python.mjs"
    for name in ("python.mjs", "python.js"):
        if (bin_dir / name).is_file():
            return name
    return "python.mjs"


def _detect_python_version(staging: Path) -> str:
    # The runtime is copied wholesale into runtime/lib/pythonX.Y.
    lib_dir = staging / "runtime" / "lib"
    if lib_dir.is_dir():
        for child in sorted(lib_dir.iterdir()):
            if child.is_dir() and child.name.startswith("python"):
                ver = child.name[len("python"):]
                if ver.count(".") == 1 and ver.replace(".", "").isdigit():
                    return ver
    return "3.13"
